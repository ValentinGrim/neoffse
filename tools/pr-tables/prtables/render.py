"""Render rows as TOML text by hand and prove the text says what the rows say.

The output is a function of the rows and the provenance: no time stamp, no
path, no tool version. The text is UTF-8, LF line ends, one `\\n` at the end.
"""

import json
import re
import tomllib
import unicodedata
from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from . import ExportError
from .build import Row
from .tables import Game

_FIELD_KEY = re.compile(r"[a-z][a-z0-9_]*")
_TABLE_KEY = re.compile(r"[A-Z][A-Z0-9_]*")


@dataclass(frozen=True)
class Provenance:
    master_bundle: str  # base name only, never a path
    master_sha256: str
    message_bundle: str
    message_sha256: str
    build_id: str | None


def toml_string(value: str) -> str:
    """A basic TOML string. Control characters are refused, never escaped."""
    for char in value:
        if unicodedata.category(char) in ("Cc", "Cs"):
            raise ExportError(f"cannot write {value!r}: control character or lone surrogate")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def file_header(game: Game, file: str, prov: Provenance, notes: Sequence[str]) -> list[str]:
    """Comment lines without the `# ` prefix."""
    build = f"build {prov.build_id}" if prov.build_id else "build unknown"
    lines = [
        f"{game.id}/{file}",
        "Generated by tools/pr-tables from the game's master data and message files.",
        "Do not edit: run the tool again (docs/architecture.md#licensing-constraints).",
        f"Game: {game.label}, Steam app {game.steam_app_id}, {build}.",
        f"Master bundle: {prov.master_bundle} (sha256 {prov.master_sha256}).",
        f"Message bundle: {prov.message_bundle} (sha256 {prov.message_sha256}).",
        "Format reference: docs/formats/pixel-remaster.md#game-master-data",
        *notes,
    ]
    return lines


def _comment_block(header: Sequence[str]) -> str:
    for line in header:
        if "\n" in line or "\r" in line:
            raise ExportError(f"header line holds a line break: {line!r}")
    return "".join(f"# {line}\n" for line in header) + "\n"


def _value(key: str, value: str | int | bool) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        if value < 0:
            raise ExportError(f"field {key}: negative integer {value}")
        return str(value)
    return toml_string(value)


def render_array(header: Sequence[str], array: str, rows: Sequence[Row]) -> str:
    if not rows:
        raise ExportError(f"array {array} has no row")
    if not _FIELD_KEY.fullmatch(array):
        raise ExportError(f"array name {array!r} is not lower-case snake case")
    entries = []
    for row in rows:
        lines = [f"[[{array}]]"]
        for key, value in row.items():
            if not _FIELD_KEY.fullmatch(key):
                raise ExportError(f"field key {key!r} is not lower-case snake case")
            lines.append(f"{key} = {_value(key, value)}")
        entries.append("\n".join(lines))
    return _comment_block(header) + "\n\n".join(entries) + "\n"


def render_table(header: Sequence[str], table: str, values: Mapping[str, int]) -> str:
    if not values:
        raise ExportError(f"table {table} has no value")
    if not _FIELD_KEY.fullmatch(table):
        raise ExportError(f"table name {table!r} is not lower-case snake case")
    lines = [f"[{table}]"]
    for key, value in values.items():
        if not _TABLE_KEY.fullmatch(key):
            raise ExportError(f"table key {key!r} is not upper-case snake case")
        lines.append(f"{key} = {_value(key, value)}")
    return _comment_block(header) + "\n".join(lines) + "\n"


def check_roundtrip(text: str, expected: Mapping[str, object]) -> None:
    """Parse `text` and require it to equal `expected`, key order included."""
    try:
        parsed = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise ExportError(f"rendered text is not TOML: {error}") from error
    if json.dumps(parsed) != json.dumps(expected):
        raise ExportError("rendered text parses to other data than the rows")
