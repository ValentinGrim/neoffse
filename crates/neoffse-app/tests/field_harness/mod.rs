//! A window that shows one `FieldEditor`, and the helpers that drive it.
//! No field of FF I has a Toggle or Choice kind, so these controls get their
//! own window and a stand-in document. Each test crate declares
//! `mod field_harness;`: Cargo does not build this folder as a test target.
#![allow(dead_code, reason = "each test crate uses a subset of the shared helpers")]
#![allow(unused_imports, reason = "each test crate uses a subset of the shared helpers")]
#![allow(clippy::unwrap_used, clippy::expect_used, reason = "a test asserts by panicking")]

use std::cell::RefCell;
use std::rc::Rc;

use i_slint_backend_testing::{AccessibleRole, ElementHandle, ElementQuery};
use slint::platform::{Key, WindowEvent};
use slint::{ComponentHandle, ModelRc, SharedString, VecModel};

mod ui {
    #![allow(unreachable_pub, reason = "generated by slint")]
    #![allow(missing_debug_implementations, reason = "generated by slint")]
    #![allow(missing_docs, reason = "generated by slint")]
    #![allow(clippy::unwrap_used, reason = "generated by slint")]
    slint::slint! {
        import { FieldEditor } from "../../ui/screens/editor/fields.slint";
        import { EditorBridge } from "../../ui/screens/editor/bridge.slint";
        import { FieldKind, FieldRow } from "../../ui/types/editor.slint";

        export { EditorBridge, FieldKind, FieldRow }

        // Wide enough for a 160 px drop-down and the raw number box beside it.
        export component Harness inherits Window {
            width: 600px;
            height: 100px;
            in property <FieldRow> data;

            FieldEditor {
                field: root.data;
            }
        }
    }
}

pub(crate) use ui::{EditorBridge, FieldKind, FieldRow, Harness};

/// The testing backend, and a window that shows no row yet.
pub(crate) fn harness() -> Harness {
    i_slint_backend_testing::init_no_event_loop();
    Harness::new().unwrap()
}

/// Runs the change handlers the event loop would run between two events.
pub(crate) fn settle() {
    slint::platform::update_timers_and_animations();
}

/// One key press and release on the window.
pub(crate) fn key(ui: &impl ComponentHandle, key: impl Into<SharedString>) {
    let text = key.into();
    ui.window().dispatch_event(WindowEvent::KeyPressed { text: text.clone() });
    ui.window().dispatch_event(WindowEvent::KeyReleased { text });
}

/// The first element with `role`, after the change handlers ran.
fn first(ui: &Harness, role: AccessibleRole) -> Option<ElementHandle> {
    settle();
    ElementQuery::from_root(ui).match_descendants().match_accessible_role(role).find_first()
}

/// The state the first check box shows.
pub(crate) fn checked(ui: &Harness) -> Option<bool> {
    first(ui, AccessibleRole::Checkbox).and_then(|element| element.accessible_checked())
}

/// The entry the first drop-down shows.
pub(crate) fn shown(ui: &Harness) -> Option<SharedString> {
    first(ui, AccessibleRole::Combobox).and_then(|element| element.accessible_value())
}

/// The text of the first text box.
pub(crate) fn typed(ui: &Harness) -> Option<SharedString> {
    first(ui, AccessibleRole::TextInput).and_then(|element| element.accessible_value())
}

/// The width of the first drop-down, in logical pixels.
pub(crate) fn combo_width(ui: &Harness) -> f32 {
    first(ui, AccessibleRole::Combobox).expect("a drop-down").size().width
}

pub(crate) fn toggle_row(checked: bool) -> FieldRow {
    FieldRow {
        kind: FieldKind::Toggle,
        editable: true,
        checked,
        ..FieldRow::default()
    }
}

/// A Choice row; `index` -1 is a value no name covers. The names model is new
/// on every call, as the view model builds one for each refresh.
pub(crate) fn choice_row(index: i32, names: &[&str]) -> FieldRow {
    let names = names.iter().map(|name| SharedString::from(*name)).collect::<Vec<_>>();
    FieldRow {
        kind: FieldKind::Choice,
        editable: true,
        known: index >= 0,
        name_index: index,
        text: index.to_string().into(),
        names: ModelRc::new(VecModel::from(names)),
        ..FieldRow::default()
    }
}

struct History<T> {
    now: T,
    before: Vec<T>,
    after: Vec<T>,
}

/// A value with an undo and a redo stack. Every change pushes the row for the
/// new value into the window, as the view model refreshes after the session
/// changes.
pub(crate) struct Document<T> {
    history: Rc<RefCell<History<T>>>,
    window: slint::Weak<Harness>,
    row: fn(T) -> FieldRow,
}

impl<T> Clone for Document<T> {
    fn clone(&self) -> Self {
        Self {
            history: Rc::clone(&self.history),
            window: self.window.clone(),
            row: self.row,
        }
    }
}

impl<T: Copy> Document<T> {
    /// Shows `start` in the window.
    pub(crate) fn new(ui: &Harness, start: T, row: fn(T) -> FieldRow) -> Self {
        ui.set_data(row(start));
        Self {
            history: Rc::new(RefCell::new(History {
                now: start,
                before: Vec::new(),
                after: Vec::new(),
            })),
            window: ui.as_weak(),
            row,
        }
    }

    fn show(&self) {
        let now = self.history.borrow().now;
        self.window.unwrap().set_data((self.row)(now));
    }

    pub(crate) fn edit(&self, value: T) {
        {
            let mut history = self.history.borrow_mut();
            let before = history.now;
            history.before.push(before);
            history.after.clear();
            history.now = value;
        }
        self.show();
    }

    pub(crate) fn undo(&self) {
        {
            let mut history = self.history.borrow_mut();
            let Some(value) = history.before.pop() else { return };
            let now = history.now;
            history.after.push(now);
            history.now = value;
        }
        self.show();
    }

    pub(crate) fn redo(&self) {
        {
            let mut history = self.history.borrow_mut();
            let Some(value) = history.after.pop() else { return };
            let now = history.now;
            history.before.push(now);
            history.now = value;
        }
        self.show();
    }
}

const NAMES: [&str; 3] = ["Alpha", "Beta", "Gamma"];

/// The three names the Choice tests use.
pub(crate) fn names() -> [&'static str; 3] {
    NAMES
}

fn named(index: i32) -> FieldRow {
    choice_row(index, &NAMES)
}

/// A Toggle row backed by a document that accepts every edit.
pub(crate) fn toggle_document(ui: &Harness, start: bool) -> Document<bool> {
    let document = Document::new(ui, start, toggle_row);
    let accept = document.clone();
    ui.global::<EditorBridge>().on_field_toggled(move |_key, checked| accept.edit(checked));
    document
}

/// A Choice row backed by a document that accepts every pick.
pub(crate) fn choice_document(ui: &Harness, start: i32) -> Document<i32> {
    let document = Document::new(ui, start, named);
    let accept = document.clone();
    ui.global::<EditorBridge>().on_field_name_picked(move |_key, index| accept.edit(index));
    document
}
