pub(crate) use ui::{Harness, Theme, ThemeId};

pub(crate) fn harness() -> Harness {
    i_slint_backend_testing::init_no_event_loop();
    Harness::new().unwrap()
}

pub(crate) fn press(ui: &Harness, text: impl Into<SharedString>) {
    let text = text.into();
    ui.window().dispatch_event(WindowEvent::KeyPressed { text: text.clone() });
    ui.window().dispatch_event(WindowEvent::KeyReleased { text });
}

pub(crate) fn key(ui: &Harness, key: Key) {
    press(ui, SharedString::from(key));
}

pub(crate) fn click_at(ui: &Harness, down: (f32, f32), up: (f32, f32)) {
    let button = PointerEventButton::Left;
    ui.window().dispatch_event(WindowEvent::PointerMoved {
        position: LogicalPosition::new(down.0, down.1),
    });
    ui.window().dispatch_event(WindowEvent::PointerPressed {
        position: LogicalPosition::new(down.0, down.1),
        button,
    });
    ui.window().dispatch_event(WindowEvent::PointerMoved {
        position: LogicalPosition::new(up.0, up.1),
    });
    ui.window().dispatch_event(WindowEvent::PointerReleased {
        position: LogicalPosition::new(up.0, up.1),
        button,
    });
}

pub(crate) fn click(ui: &Harness, x: f32, y: f32) {
    click_at(ui, (x, y), (x, y));
}

pub(crate) fn by_label(ui: &Harness, label: &str) -> ElementHandle {
    ElementHandle::find_by_accessible_label(ui, label)
        .next()
        .unwrap_or_else(|| panic!("no element is labelled {label}"))
}
