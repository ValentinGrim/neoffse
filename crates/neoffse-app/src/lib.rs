/// Builds the windows, wires them together and runs the event loop.
///
/// # Errors
///
/// Returns the platform error when a window or the event loop cannot start.
pub fn run() -> Result<(), slint::PlatformError> {
    let language = system_language();
    let registry = Arc::new(Registry::new(language));
    let app = App::new(
        registry,
        language,
        Environment::platform(),
        Arc::new(NativePicker),
        Arc::new(EventLoopDispatcher),
    );
    // The only place that names the platform data folder. A missing one leaves
    // the data folder unset: a save and a restore then both end in the generic
    // failure notice. A distinct notice waits for the translated catalogue
    // (`docs/architecture.md#layers-and-milestone-boundaries`).
    if let Ok(data) = DataDir::platform() {
        app.state.set_data_dir(data);
    }
    let main_window = MainWindow::new()?;
    let about = new_about_dialog()?;
    connect_about(&main_window, &about);
    connect_quit(&main_window);
    connect_home(&main_window, &app);
    connect_editor(&main_window, &app);
    connect_history(&main_window, &app);
    connect_review(&main_window, &app);
    connect_save(&main_window, &app);
    connect_restore(&main_window, &app);
    connect_expert(&main_window, &app);
    connect_close(&main_window, &about, &app);
    main_window.run()
}

/// Creates the About dialog with the version and license taken from the
/// crate manifest, so each has one source, and the two font credits.
///
/// # Errors
///
/// Returns the platform error when the dialog cannot be created.
pub fn new_about_dialog() -> Result<AboutDialog, slint::PlatformError> {
    let about = AboutDialog::new()?;
    about.set_app_version(env!("CARGO_PKG_VERSION").into());
    about.set_license(env!("CARGO_PKG_LICENSE").into());
    about.set_font_credit(font_credit());
    about.set_ui_font_credit(ui_font_credit());
    Ok(about)
}

/// Opens `about` from the menu and hides it on dismiss. It also hides the
/// dialog when the main window closes, until [`connect_close`] replaces that
/// handler.
///
/// The main window's About callback holds a strong reference, so the
/// dialog outlives the caller's handle. The dialog's own callbacks hold
/// weak ones, so no reference cycle forms.
pub fn connect_about(main_window: &MainWindow, about: &AboutDialog) {
    let dialog = about.clone_strong();
    main_window.on_about_requested(move || {
        // A failed show or hide leaves nothing to recover, and the app has no logger.
        let _ = dialog.show();
    });

    let weak = about.as_weak();
    about.on_dismiss(move || {
        if let Some(dialog) = weak.upgrade() {
            let _ = dialog.hide();
        }
    });

    // Without this hide, an open About dialog keeps the event loop, and the
    // process, alive after the main window closes. `connect_close` replaces
    // this handler and hides the dialog itself.
    let weak = about.as_weak();
    main_window.window().on_close_requested(move || {
        if let Some(dialog) = weak.upgrade() {
            let _ = dialog.hide();
        }
        CloseRequestResponse::HideWindow
    });
}

/// Sends the close request of the window's close button when the user picks
/// File > Quit, so the handler [`connect_close`] installs decides: a dirty
/// session gets the discard question, a dialog over the page or a running save,
/// reload or restore vetoes, and a clean session closes and hides About.
///
/// The window looks the handler up when the request fires, so the order of
/// `connect_quit` and `connect_close` does not matter.
pub fn connect_quit(main_window: &MainWindow) {
    let weak = main_window.as_weak();
    main_window.on_quit_requested(move || {
        if let Some(window) = weak.upgrade() {
            window.window().dispatch_event(WindowEvent::CloseRequested);
        }
    });
}
